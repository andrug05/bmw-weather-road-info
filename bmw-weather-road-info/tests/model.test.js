'use strict';
const assert = require('assert');
const M = require('../apps/aurelm_weather_traffic/model');
assert(M.validCoordinates(47.01, 28.86));
assert(!M.validCoordinates(100, 28));
assert.strictEqual(M.formatTemperature(12.6), '13°');
const roads = M.normalizeRoadFeature({ id: 12, tags: { name: 'Main St', highway: 'construction', maxspeed: '30' } });
assert.strictEqual(roads.name, 'Main St');
assert(roads.type.includes('Road construction'));
console.log('model tests passed');
