'use strict';
const assert = require('assert');
const M = require('../apps/aurelm_weather_traffic/model');
assert(M.validCoordinates(47.01, 28.86));
assert(!M.validCoordinates(100, 28));
assert.strictEqual(M.formatTemperature(12.6), '13°');
assert.strictEqual(M.weatherLabel(0), 'Clear');
const roads = M.normalizeRoadFeature({ id: 12, tags: { name: 'Main St', highway: 'construction', maxspeed: '30' } });
assert.strictEqual(roads.name, 'Main St');
assert(roads.type.includes('Road construction'));
const w = M.normalizeWeather({ current: { temperature_2m: 10, apparent_temperature: 8, relative_humidity_2m: 50, wind_speed_10m: 12, precipitation: 0, weather_code: 1 }, hourly: { time: ['10:00'], temperature_2m: [10], precipitation_probability: [0], weather_code: [1] }, daily: { time: ['2026-11-05'], temperature_2m_min: [4], temperature_2m_max: [12], weather_code: [1], precipitation_probability_max: [0] } });
assert.strictEqual(w.temperature, 10);
assert.strictEqual(w.daily.length, 1);
console.log('model tests passed');
